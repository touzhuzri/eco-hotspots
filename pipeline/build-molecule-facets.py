"""
Build class/family facets for browsing and filtering.

Input : data/molecules/<XX>.json.gz  (generated by build-molecule-meta.py)
Output: data/molecules/facets.json.gz

facets.json.gz:
{
  "classes":  [{ "name": "...", "count": N }, ...],
  "families": [{ "name": "...", "count": N }, ...],
  "map": { "<InChIKey>": [classIndex, familyIndex], ... }
}
"""

import glob
import gzip
import json
import os
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN_DIR = os.path.join(ROOT, "data", "molecules")
OUT = os.path.join(IN_DIR, "facets.json.gz")
UNKNOWN_CLASS = "未细分化学类别"
UNKNOWN_FAMILY = "未标注科"


def main():
    class_counts = Counter()
    family_counts = Counter()
    rows = {}
    for path in sorted(glob.glob(os.path.join(IN_DIR, "??.json.gz"))):
        with gzip.open(path, "rt", encoding="utf-8") as fh:
            shard = json.load(fh)
        for key, row in shard.items():
            npclass = row[4] if isinstance(row, list) and len(row) > 4 else []
            cls = npclass[-1] if npclass else UNKNOWN_CLASS
            fam = (row[6] if isinstance(row, list) and len(row) > 6 else "") or UNKNOWN_FAMILY
            class_counts[cls] += 1
            family_counts[fam] += 1
            rows[key] = (cls, fam)

    classes = sorted(class_counts.items(), key=lambda x: (-x[1], x[0]))
    families = sorted(family_counts.items(), key=lambda x: (-x[1], x[0]))
    class_idx = {name: i for i, (name, _) in enumerate(classes)}
    family_idx = {name: i for i, (name, _) in enumerate(families)}

    payload = {
        "classes": [{"name": n, "count": c} for n, c in classes],
        "families": [{"name": n, "count": c} for n, c in families],
        "map": {
            key: [class_idx[cls], family_idx[fam]]
            for key, (cls, fam) in rows.items()
        },
    }

    with gzip.open(OUT, "wt", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))

    print(
        "classes",
        len(classes),
        "families",
        len(families),
        "keys",
        len(rows),
        "size",
        round(os.path.getsize(OUT) / 1e6, 2),
        "MB",
    )
    print("top classes", classes[:10])
    print("top families", families[:10])


if __name__ == "__main__":
    main()
