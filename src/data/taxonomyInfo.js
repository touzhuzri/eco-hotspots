export function classInfoFor(meta) {
  const candidates = [
    meta?.npclass?.[meta.npclass.length - 1],
    meta?.classyfire,
    meta?.npclass?.[1],
    meta?.npclass?.[0],
  ].filter(Boolean);
  for (const c of candidates) {
    if (CLASS_INFO[c]) return { label: c, ...CLASS_INFO[c] };
  }
  return {
    label: candidates[0] || "天然产物",
    zh: "天然产物",
    text:
      "LOTUS 尚未为该分子细分到可解释的化学类别。它仍是一条结构–物种关联记录；可以结合分子式、结构描述符和来源物种理解其基本特征。",
  };
}

export function familyInfoFor(family) {
  if (!family) return null;
  return FAMILY_INFO[family] || null;
}

/** 按类群/树层给出生态语境 */
export function ecologyText(kingdom, layer) {
  if (kingdom === "真菌") {
    return "真菌次级代谢物常参与竞争、防御、共生或寄生互作；土壤和枯落物中的真菌尤其常见这类化学交流。";
  }
  if (kingdom === "细菌") {
    return "细菌（尤其是放线菌）是抗生素、铁载体和信号分子的重要来源，常通过次级代谢物参与竞争与群体感应。";
  }
  if (kingdom === "昆虫") {
    return "昆虫来源分子常与防御、信息素、寄主识别和种间互作有关。";
  }
  if (kingdom === "生态角色") {
    return "这是一个生态叙事挂点，重点在生态网络与过程，而不是单一分子的化学活性。";
  }
  if (layer === "canopy") {
    return "冠层叶片和嫩枝是植物次生代谢最活跃的部位之一，常见与紫外防护、抗微生物、抗食草动物和传粉吸引相关的化合物。";
  }
  if (layer === "trunk") {
    return "树皮和木质部中的成分常与结构支撑、伤口保护、抗腐朽和防御相关。";
  }
  if (layer === "rhizosphere") {
    return "根际和根系分泌物参与养分获取、化感作用、共生信号和微生物互作。";
  }
  if (layer === "soil") {
    return "土壤和枯落物中的植物成分参与分解、养分循环和微生物互作。";
  }
  return "该分子来自 LOTUS 的物种–结构关联记录，具体生态角色需要结合来源物种和栖息环境理解。";
}
